#!/bin/bash
# Applies palette.env to every component. Re-run after changing the palette.
set -e; C=/workspace/osbuilder/config; cd $C; source palette.env
hex(){ echo "$1"; }
# ---- tint2 (both panels) ----
for f in tint2rc tint2-shelf-apps.rc; do
python3 - "$f" "$SURFACE" "$SURFACE_VARIANT" "$ACCENT_CONTAINER" "$ON_SURFACE" <<'PY'
import sys,re
p,surf,var,acc,fg=sys.argv[1:]
s=open(p).read()
blocks=s.split('# --- backgrounds (must come first) ---')[1].split('\n\n')[0]
nb=f"""
# 1 panel: surface
rounded = 0
border_width = 0
background_color = {surf} 100
border_color = #000000 0
# 2 task button
rounded = 20
border_width = 0
background_color = #ffffff 0
border_color = #000000 0
background_color_hover = {var} 100
# 3 active task
rounded = 20
border_width = 0
background_color = {acc} 100
border_color = #000000 0
# 4 status pill
rounded = 18
border_width = 0
background_color = {var} 100
border_color = #000000 0"""
s=s.replace(blocks,nb)
s=re.sub(r'clock_font_color = .*',f'clock_font_color = {fg} 100',s)
open(p,'w').write(s)
PY
done
# ---- status pills ----
sed -i "s|^BG=.*; FG=.*; FONT=|BG='$SURFACE_VARIANT'; FG='$ON_SURFACE'; BADGE_FG='$SURFACE'; FONT=|" status/render-status.sh
sed -i "s|-fill '#[0-9a-fA-F]*' -gravity center -annotate|-fill \"\$BADGE_FG\" -gravity center -annotate|" status/render-status.sh
rm -rf /tmp/osb-status
cp brand/polderos-logo-64.png launcher-icon.png   # Polder OS mark as launcher button
# ---- rofi launcher ----
cat > launcher.rasi <<R
* { font: "Roboto 12"; background-color: transparent; text-color: $ON_SURFACE; }
window { width: 640px; location: south west; anchor: south west; x-offset: 10px; y-offset: -62px; border: 0px; padding: 0px; background-color: transparent; background-image: url("$C/launcher-bg.png", none); }
mainbox { background-color: $SURFACE; border-radius: 22px; padding: 18px; }
inputbar { background-color: $SURFACE_VARIANT; border-radius: 20px; padding: 10px 16px; children: [entry]; }
entry { placeholder: "Zoek op je apparaat, in apps, op internet..."; placeholder-color: $ON_SURFACE_VARIANT; }
listview { columns: 5; lines: 3; layout: vertical; spacing: 10px; margin: 14px 0 0 0; fixed-height: true; }
element { orientation: vertical; padding: 10px; border-radius: 14px; }
element selected { background-color: $ACCENT_CONTAINER; text-color: $ON_ACCENT_CONTAINER; }
element-icon { size: 48px; horizontal-align: 0.5; }
element-text { horizontal-align: 0.5; font: "Roboto 10"; text-color: inherit; }
R
# ---- quick settings ----
cat > quicksettings/qs.css <<Q
/* generated by build-theme.sh from palette.env */
* { font-family: Roboto; }
#panel { background-color: $SURFACE; border-radius: 24px; padding: 16px; color: $ON_SURFACE; }
.pill { background: $SURFACE_VARIANT; border: none; box-shadow: none; border-radius: 16px; padding: 4px 12px; min-height: 24px; color: $ON_SURFACE; font-weight: 500; font-size: 12px; }
.tile { background: $SURFACE_VARIANT; border: none; box-shadow: none; border-radius: 22px; padding: 6px 14px; min-height: 48px; color: $ON_SURFACE; }
.tile:hover { background: shade($SURFACE_VARIANT, 0.96); }
.tile:checked { background: $ACCENT_CONTAINER; color: $ON_ACCENT_CONTAINER; }
.tile:checked .sub { color: $ON_ACCENT_CONTAINER; }
.tile .title { font-weight: 500; font-size: 13px; }
.tile .sub { font-size: 11px; color: $ON_SURFACE_VARIANT; }
.dot { min-width: 8px; min-height: 8px; padding: 0; border-radius: 4px; background: $OUTLINE; border: none; box-shadow: none; }
.dot.on { background: $ACCENT; min-width: 20px; }
scale { padding: 0; }
scale trough { min-height: 36px; border-radius: 18px; background: $SURFACE_VARIANT; border: none; }
scale highlight { min-height: 36px; border-radius: 18px; background: $ACCENT_CONTAINER; border: none; }
scale slider { min-width: 36px; min-height: 36px; margin: 0; border-radius: 18px; background: $ACCENT; border: none; box-shadow: none; }
.knobicon { color: $ON_ACCENT_CONTAINER; }
.round { background: $SURFACE_VARIANT; border: none; box-shadow: none; border-radius: 20px; min-width: 36px; min-height: 36px; padding: 0; color: $ON_SURFACE; }
.avatar { background: $ACCENT; color: $ON_ACCENT; border-radius: 18px; min-width: 36px; min-height: 36px; font-weight: 500; }
.battery { color: $ON_SURFACE; font-size: 13px; }
#histcard { background-color: $SURFACE; border-radius: 24px; padding: 16px; color: $ON_SURFACE; }
.histtitle { font-weight: 500; font-size: 14px; }
.tile.mini { min-height: 40px; min-width: 40px; padding: 0; border-radius: 20px; }
Q
# ---- GTK (all apps in session, incl. Thunar & dialogs) ----
cat > files/gtk.css <<G
/* generated by build-theme.sh from palette.env */
@define-color theme_bg_color $SURFACE; @define-color theme_base_color $SURFACE;
@define-color theme_fg_color $ON_SURFACE; @define-color theme_text_color $ON_SURFACE;
@define-color theme_selected_bg_color $ACCENT_CONTAINER; @define-color theme_selected_fg_color $ON_ACCENT_CONTAINER;
* { font-family: Roboto; }
window, .background, treeview.view, scrolledwindow, viewport, placessidebar, .sidebar, paned { background-color: $SURFACE; color: $ON_SURFACE; }
treeview.view header button { background: $SURFACE; border: none; border-bottom: 1px solid $OUTLINE; color: $ON_SURFACE_VARIANT; font-weight: 500; padding: 8px 12px; box-shadow: none; }
treeview.view:selected, treeview.view:selected:focus, .sidebar:selected, placessidebar row:selected { background-color: $ACCENT_CONTAINER; color: $ON_ACCENT_CONTAINER; }
treeview.view:hover { background-color: $SURFACE_VARIANT; }
toolbar, .toolbar, headerbar, .path-bar { background: $SURFACE; border: none; box-shadow: none; }
toolbar { padding: 6px 10px; }
toolbar button, .path-bar button { background: transparent; border: none; box-shadow: none; border-radius: 18px; color: $ON_SURFACE_VARIANT; min-height: 32px; }
.path-bar button { font-size: 15px; color: $ON_SURFACE; }
toolbar button:hover, .path-bar button:hover { background: $SURFACE_VARIANT; }
paned > separator { background: $OUTLINE; min-width: 1px; }
entry { background: $SURFACE_VARIANT; border: none; border-radius: 18px; color: $ON_SURFACE; }
button { border-radius: 18px; }
menu, .menu, .context-menu { background-color: $SURFACE; border-radius: 10px; padding: 6px 0; border: 1px solid $OUTLINE; }
menu menuitem { min-height: 30px; padding: 0 22px; color: $ON_SURFACE; }
menu menuitem:hover { background-color: $SURFACE_VARIANT; color: $ON_SURFACE; }
menu menuitem accelerator { color: $ON_SURFACE_VARIANT; }
menu separator { background: $OUTLINE; margin: 2px 0; min-height: 1px; }
messagedialog .dialog-action-area button { background: $SURFACE_VARIANT; border: none; color: $ON_SURFACE; }
G
# GTK theme as a real theme dir (Arc/Arc-Dark base + our overrides). GTK only reloads on a theme NAME change,
# and GTK caches themes by name for the life of the process -> every build gets a NEW name (PolderOS-GTK-<n>);
# point xsettings (xfsettingsd) at it and running apps restyle live.
BASE=Arc; [ "${THEME:-light}" = dark ] && BASE=Arc-Dark
TD=/tmp/protohome/.local/share/themes; mkdir -p $TD   # $XDG_DATA_HOME/themes: found even by Files (which runs with its own HOME)
SLOTF=~/.config/osb/gtkslot; mkdir -p ~/.config/osb; SLOT=$(( $(cat $SLOTF 2>/dev/null || echo 0) + 1 )); echo $SLOT > $SLOTF
for o in $TD/PolderOS-GTK-*; do [ -e "$o" ] && [ "$o" != $TD/PolderOS-GTK-$SLOT ] && [ "$o" != $TD/PolderOS-GTK-$((SLOT-1)) ] && rm -rf "$o"; done
G3=$TD/PolderOS-GTK-$SLOT/gtk-3.0; rm -rf $G3; mkdir -p $G3
for f in /usr/share/themes/$BASE/gtk-3.0/*; do case $(basename $f) in gtk.css|gtk-dark.css) ;; *) ln -s $f $G3/;; esac; done   # gtk.gresource etc.
{ cat /usr/share/themes/$BASE/gtk-3.0/gtk.css; echo; python3 $C/osb/boost-css.py files/gtk.css; } > $G3/gtk.css
cp $G3/gtk.css $G3/gtk-dark.css   # apps that asked for a dark variant must still get OUR palette (light or dark)
rm -f /tmp/protohome/.config/gtk-3.0/gtk.css   # old user-level override would mask theme changes
mkdir -p /tmp/protohome/.config/gtk-3.0; sed "s/^gtk-theme-name=.*/gtk-theme-name=PolderOS-GTK-$SLOT/" gtkrc-settings.ini > /tmp/protohome/.config/gtk-3.0/settings.ini
xfconf-query -c xsettings -p /Net/ThemeName -n -t string -s PolderOS-GTK-$SLOT 2>/dev/null || xfconf-query -c xsettings -p /Net/ThemeName -s PolderOS-GTK-$SLOT 2>/dev/null || true
# ---- xfwm4 theme "Polder OS" ----
T=$C/xfwm4-theme/PolderOS/xfwm4; rm -rf $T; mkdir -p $T
TH=36
for st in active inactive; do
  FG=$ON_SURFACE; [ $st = inactive ] && FG=$ON_SURFACE_VARIANT
  for i in 1 2 3 4 5; do convert -size 4x$TH xc:"$SURFACE" $T/title-$i-$st.png; done
  convert -size 8x$TH xc:"$SURFACE" -fill "$OUTLINE" -draw "line 0,0 0,$TH" $T/top-left-$st.png
  convert -size 8x$TH xc:"$SURFACE" -fill "$OUTLINE" -draw "line 7,0 7,$TH" $T/top-right-$st.png
  convert -size 1x4 xc:"$OUTLINE" $T/left-$st.png; cp $T/left-$st.png $T/right-$st.png
  convert -size 4x1 xc:"$OUTLINE" $T/bottom-$st.png
  convert -size 1x1 xc:"$OUTLINE" $T/bottom-left-$st.png; cp $T/bottom-left-$st.png $T/bottom-right-$st.png
  for b in close hide maximize menu shade stick; do
   for v in $st $( [ $st = active ] && echo "prelight pressed" ); do
    BGC=$SURFACE; [ $v = prelight ] && BGC=$SURFACE; CIRC=none; [ $v = prelight ] && CIRC=$SURFACE_VARIANT; [ $v = pressed ] && CIRC=$ACCENT_CONTAINER
    D=""; case $b in close) D="line 13,13 23,23 line 23,13 13,23";; hide) D="line 13,22 23,22";; maximize) D="rectangle 13,13 23,23";; esac
    convert -size 36x$TH xc:"$BGC" -fill "$CIRC" -stroke none -draw "circle 18,18 18,4" -fill none -stroke "$FG" -strokewidth 1.6 -draw "$D" $T/$b-$v.png
   done; done
done
cat > $T/themerc <<X
active_text_color=$ON_SURFACE
inactive_text_color=$ON_SURFACE_VARIANT
title_alignment=center
full_width_title=true
title_vertical_offset_active=0
title_vertical_offset_inactive=0
button_spacing=2
button_offset=6
title_shadow_active=false
title_shadow_inactive=false
X
mkdir -p ~/.themes; rm -rf ~/.themes/PolderOS; cp -r $C/xfwm4-theme/PolderOS ~/.themes/
# ---- backdrops for rounded launcher (QS makes its own at runtime) ----
convert wallpaper.png -crop 640x372+10+334 +repage -separate -swap 0,2 -combine launcher-bg.png
echo "theme built"
