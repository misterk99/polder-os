#!/usr/bin/env python3
"""Apply Polder OS settings to the running session. usage: apply.py theme|kbd|shelf|night|palette ...
'palette' only regenerates files (no running processes touched), used early in start-session.sh."""
import os, sys, subprocess, glob, shutil
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import osbsettings as S
C = S.CFG

def sh(*a, t=30):
    try: return subprocess.run(a, capture_output=True, text=True, timeout=t).stdout
    except Exception as e: print('apply:', a[0], e, file=sys.stderr); return ''

def spawn(*a, log='/dev/null'):
    subprocess.Popen(a, stdout=open(log, 'a'), stderr=subprocess.STDOUT, start_new_session=True)

def write_palette(s):
    th = S.effective_theme(s); p = S.palette_for(th, s['accent'])
    lines = ['# GENERATED by osb/apply.py from ~/.config/osb/settings.json (theme=%s, accent=%s). Edit via Instellingen.' % (th, s['accent']),
             f'THEME={th}'] + [f'{k}={v}' for k, v in p.items()]
    open(os.path.join(C, 'palette.env'), 'w').write('\n'.join(lines) + '\n')
    wp = os.path.join(C, 'wallpapers', s['wallpaper'] + '.png')
    dark_wp = os.path.join(C, 'wallpapers', s['wallpaper'] + '-avond.png')   # e.g. Polderheuvel has an evening variant
    if th == 'dark' and os.path.exists(dark_wp): wp = dark_wp
    if os.path.exists(wp): shutil.copyfile(wp, os.path.join(C, 'wallpaper.png'))

def palette(s):
    write_palette(s); sh(os.path.join(C, 'build-theme.sh'), t=120)
    for f in glob.glob('/tmp/osb-*-bg*.png') + glob.glob('/tmp/osb-notify/bg-*.png') + glob.glob('/tmp/osb-wall*'):
        try: os.remove(f)
        except OSError: pass

def wayland_theme(s):
    """Rev 34h: live theme on polder-comp. GTK3 Wayland apps follow GSettings (org.gnome.desktop.interface, dconf) live;
    X11 apps under Xwayland follow XSETTINGS from xsettingsd (HUP = reload). The shelf/desktop reload palette.env + wallpaper.png by mtime."""
    slot = open(os.path.expanduser('~/.config/osb/gtkslot')).read().strip()
    dark = S.effective_theme(s) == 'dark'; name = f'PolderOS-GTK-{slot}'
    for k, v in (('gtk-theme', name), ('color-scheme', 'prefer-dark' if dark else 'default'), ('icon-theme', 'Papirus'), ('font-name', 'Roboto 10')):
        sh('gsettings', 'set', 'org.gnome.desktop.interface', k, v)
    conf = os.path.expanduser('~/.config/xsettingsd/xsettingsd.conf'); os.makedirs(os.path.dirname(conf), exist_ok=True)
    open(conf, 'w').write(f'Net/ThemeName "{name}"\nNet/IconThemeName "Papirus"\nGtk/FontName "Roboto 10"\nGtk/ApplicationPreferDarkTheme {int(dark)}\n')
    if os.environ.get('DISPLAY'):   # Xwayland
        if sh('pkill', '-HUP', '-x', 'xsettingsd') == '' and subprocess.run(['pgrep', '-x', 'xsettingsd'], capture_output=True).returncode != 0:
            spawn('xsettingsd', '-c', conf, log='/tmp/xsettingsd.log')
    for p in ('quicksettings/qs.py', 'calendar/cal.py'): sh('pkill', '-f', p)
    sh('pkill', '-f', 'notify/osb-notifyd.py'); spawn('python3', os.path.join(C, 'notify/osb-notifyd.py'), log='/tmp/osb-notifyd.log')

def theme(s):
    palette(s)
    if os.environ.get('POLDER_COMP') and os.environ.get('WAYLAND_DISPLAY'): wayland_theme(s); return
    sh('feh', '--bg-fill', os.path.join(C, 'wallpaper.png'))
    sh('pkill', '-USR1', '-x', 'tint2')                                     # shelf reload
    sh('xfconf-query', '-c', 'xfwm4', '-p', '/general/theme', '-s', 'Default')  # xfwm4 only reloads on a name change
    sh('xfconf-query', '-c', 'xfwm4', '-p', '/general/theme', '-s', 'PolderOS')
    for p in ('quicksettings/qs.py', 'calendar/cal.py'): sh('pkill', '-f', p)  # popups are short-lived; reopen in new colours
    if os.environ.get('POLDER_SHELL'):    # Revision 27: notifications live in polder-shell -> reload its CSS in place
        import shellipc; shellipc.send('notify-reload')
    else:
        sh('pkill', '-f', 'notify/osb-notifyd.py')                              # restart daemon (history lives in state.json)
        spawn('python3', os.path.join(C, 'notify/osb-notifyd.py'), log='/tmp/osb-notifyd.log')
    os.makedirs('/tmp/osb-lockbg', exist_ok=True); os.chmod('/tmp/osb-lockbg', 0o1777)   # shared with the box-only lock test account
    spawn('env', 'OSB_LOCK_CACHE=/tmp/osb-lockbg', 'python3', os.path.join(C, 'lock/lockui.py'), '--prerender', log='/tmp/osb-lockbg.log')  # blurred lock bg

def kbd(s):
    a = ['setxkbmap', s['kbd_layout']] + (['-variant', s['kbd_variant']] if s.get('kbd_variant') else [])
    sh(*a); shelf(s)

def shelf(s):
    shutil.rmtree('/tmp/osb-status', ignore_errors=True); sh('pkill', '-USR1', '-x', 'tint2')

def night(s):
    out = next((l.split()[0] for l in sh('xrandr', '-q').splitlines() if ' connected' in l), None)
    if out: sh('xrandr', '--output', out, '--gamma', '1:0.82:0.64' if s.get('night_light') else '1:1:1')

if __name__ == '__main__':
    s = S.load()
    for what in sys.argv[1:]: globals()[what](s)
